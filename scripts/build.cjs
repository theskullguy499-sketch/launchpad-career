// Deterministic browser SDK + explicit Pages artifact. npm ci verifies lockfile integrity.
const fs = require('node:fs/promises');
const path = require('node:path');
const { createHash } = require('node:crypto');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
async function main() {
  require('./public-config.cjs')(await fs.readFile(path.join(root,'auth-config.js'),'utf8'));
  const pkg = JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
  const sdk = JSON.parse(await fs.readFile(path.join(root,'node_modules/@supabase/supabase-js/package.json'),'utf8'));
  if (pkg.dependencies['@supabase/supabase-js'] !== sdk.version || pkg.devDependencies.esbuild !== esbuild.version) throw new Error('Installed tools do not match exact package pins. Run npm ci.');
  const result = await esbuild.build({absWorkingDir:root,entryPoints:['node_modules/@supabase/supabase-js/dist/index.mjs'],bundle:true,format:'esm',platform:'browser',target:['es2022'],outfile:'vendor/supabase.js',minify:true,legalComments:'eof',write:false,metafile:true});
  const bundle = result.outputFiles[0].contents;
  const packageDirs = new Set();
  for (const file of Object.keys(result.metafile.inputs)) {
    const parts = file.split('/');const index = parts.lastIndexOf('node_modules');
    if (index !== -1) packageDirs.add(parts.slice(0,index+(parts[index+1].startsWith('@')?3:2)).join('/'));
  }
  let notices = 'Third-party packages included in vendor/supabase.js. Generated by npm run build.\n';
  for (const dir of [...packageDirs].sort()) {
    const metadata = JSON.parse(await fs.readFile(path.join(root,dir,'package.json'),'utf8'));
    const files = (await fs.readdir(path.join(root,dir))).filter(f=>/^licen[sc]e(?:\.|$)/i.test(f)).sort();
    if (!files.length) throw new Error(`Missing license for ${metadata.name}`);
    notices += `\n===== ${metadata.name}@${metadata.version} (${metadata.license}) =====\n`;
    for (const file of files) notices += (await fs.readFile(path.join(root,dir,file),'utf8')).replace(/\r\n/g,'\n').trim()+'\n';
  }
  const manifest = JSON.stringify({supabase:sdk.version,esbuild:esbuild.version,target:'es2022',sha256:{'supabase.js':sha(bundle),'LICENSES.txt':sha(notices)}},null,2)+'\n';
  const vendor = {'supabase.js':bundle,'LICENSES.txt':notices,'manifest.json':manifest};
  for (const [file,bytes] of Object.entries(vendor)) {
    const destination = path.join(root,'vendor',file);
    if (process.argv.includes('--check')) {
      if (!(await fs.readFile(destination)).equals(Buffer.from(bytes))) throw new Error(`${destination} is stale. Run npm run build and commit the generated vendor files.`);
    } else {await fs.mkdir(path.dirname(destination),{recursive:true});await fs.writeFile(destination,bytes);}
  }
  if (process.argv.includes('--check')) { console.log('Committed SDK bundle, versions, licenses and hashes match the reproducible build.');return; }
  const publicFiles = ['assets/launchpad.svg','index.html','tracker.js','platform.js','styles/platform.css','lib/model.mjs','lib/workspace.mjs','data/companies.mjs','data/countries.mjs','legal/privacy.html','legal/terms.html','auth.js','auth-client.js','cloud-data.js','auth-config.js','auth/callback.html','auth/callback.js','.nojekyll',...Object.keys(vendor).map(f=>`vendor/${f}`)];
  const output = path.join(root,'_site');
  await fs.rm(output,{recursive:true,force:true});
  const hashes = {};
  for (const file of publicFiles) {
    const bytes = await fs.readFile(path.join(root,file));hashes[file] = sha(bytes);
    const destination=path.join(output,file);await fs.mkdir(path.dirname(destination),{recursive:true});await fs.writeFile(destination,bytes);
  }
  await fs.writeFile(path.join(output,'build-manifest.json'),JSON.stringify({supabase:sdk.version,files:hashes},null,2)+'\n');
  console.log(`Built pinned Supabase ${sdk.version}; staged ${publicFiles.length} public files in _site/.`);
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
